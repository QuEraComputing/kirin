/// Wrapper enum that composes all wildcard statements.
#[derive(Debug, Clone, PartialEq, Eq, Hash, Dialect, PrettyPrint)]
#[wraps]
#[kirin(builders, type = T)]
#[chumsky(format = "wildcard")]
pub enum PatternStatement<T: CompileTimeValue> {
    Pattern(Pattern<T>),
    Hole(Hole<T>),
    NativeCall(NativeCall<T>),
    Constraint(Constraint<T>),
    Replace(Replace<T>),
    Erase(Erase<T>),
    Rewrite(Rewrite<T>),
    Advance(Advance<T>),
    Skip(Skip<T>),
    Interrupt(Interrupt<T>),
    WalkResultOf(WalkResultOf<T>),
}
